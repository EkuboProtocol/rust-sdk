#!/usr/bin/env python3
"""Writes ZeroSeedLaunchSdkParityV2.t.sol, the parity generator for the tick-rate fee model
(evm-contracts 3d6378f, `uint64 decayRateX32`), from ZeroSeedLaunchSdkParity.t.sol (43d6628,
`uint32 feeDuration`). The swap program and every logged value are unchanged; only the fee
parameter, its log key, the LaunchCreated signature and the scenarios that exercise the rate differ.

Program horizons keep their names (3600 and 600 seconds of trading). The decay rate of a scenario is
the 600 s half-life rate on the 3600 s horizon (so the program sees the fee fall well below its
start) and the default one-day rate on the 600 s horizon; the rate scenarios override it with 0
(flat), 1 (slowest), 2**64 - 1 (floor from the first second) and 2**30 (a fractional quarter tick
per second).

Usage: python3 make_tick_rate_parity.py  (run from this directory; rewrites the V2 file)"""
import re
from pathlib import Path

here = Path(__file__).parent
src = (here / "ZeroSeedLaunchSdkParity.t.sol").read_text()


def sub(pattern, repl, text, count=1, flags=0):
    out, n = re.subn(pattern, repl, text, count=0 if count is None else count, flags=flags)
    assert n == count or (count is None and n > 0), (pattern, n)
    return out


s = src
s = sub(
    r"// EkuboProtocol/evm-contracts@43d6628841b3ce91dafa048b7ceef64bed55fc8e as test/extensions/, run with\n// `forge test --offline --match-contract ZeroSeedLaunchSdkParity -vv`",
    "// EkuboProtocol/evm-contracts@3d6378f585591dc7eabeea6976932c30524bb8ea as test/extensions/, run with\n"
    "// `forge test --offline --match-contract ZeroSeedLaunchSdkParityV2 -vv`",
    s,
)
s = sub(
    r"^pragma solidity =0\.8\.33;\n",
    "pragma solidity =0.8.33;\n\n// GENERATED by make_tick_rate_parity.py from ZeroSeedLaunchSdkParity.t.sol: the tick-rate fee model.\n",
    s,
    flags=re.M,
)
s = sub(r"contract ZeroSeedLaunchSdkParityTest is", "contract ZeroSeedLaunchSdkParityV2Test is", s)
s = sub(
    r"uint32,uint64,uint32,uint64,uint64,bytes32\)\)",
    "uint32,uint64,uint64,uint64,uint64,bytes32))",
    s,
)
s = sub(
    r"    LaunchTestRouter router;\n",
    """    LaunchTestRouter router;

    /// @dev Trading horizons of the swap program, in seconds; not fee parameters.
    uint32 constant DURATION = 3600;
    uint32 constant DURATION_SHORT = 600;
    bool rateOverridden;
    uint64 rateOverride;

    /// @dev The decay rate of a scenario on a horizon, unless a rate scenario overrides it.
    function _rateFor(uint32 horizon) private view returns (uint64) {
        if (rateOverridden) return rateOverride;
        return horizon == DURATION ? DECAY_RATE_600 : DECAY_RATE;
    }
""",
    s,
)
s = sub(r"_parameters\(([^;]*?), (duration|DURATION)\)", r"_parameters(\1, _rateFor(\2))", s, count=None)
s = sub(r'"\|feeDuration=",\n(\s*)_s\((ep|p)\.feeDuration\)', r'"|decayRateX32=",\n\1_s(\2.decayRateX32)', s, count=2)
s = sub(
    r'r\.feeDuration = 0;\n(\s*)_logPreview\(string\.concat\(g, "_duration0"\), r\);',
    r'r.decayRateX32 = 0;\n\1_logPreview(string.concat(g, "_rate0"), r);',
    s,
)
s = sub(
    r'r\.feeDuration = type\(uint32\)\.max;\n(\s*)_logPreview\(string\.concat\(g, "_durationMax"\), r\);',
    r'r.decayRateX32 = type(uint64).max;\n\1_logPreview(string.concat(g, "_rateMax"), r);',
    s,
)
s = sub(
    r"(    /// @dev A launch near the top of the price range)",
    """    /// @dev The program at a fixed decay rate: flat, slowest, floor from the first second, fractional.
    function _rateScenario(bool tokenIs0, uint8 quoteDecimals, uint64 rate, string memory name) private {
        rateOverridden = true;
        rateOverride = rate;
        _highRateScenario(tokenIs0, quoteDecimals, DURATION, 9223372036854775808, name);
        rateOverridden = false;
    }

    function test_parity_rate_zero() public {
        _rateScenario(true, 18, 0, "rateZero");
    }

    function test_parity_rate_one_native() public {
        _rateScenario(false, 18, 1, "rateOne");
    }

    function test_parity_rate_max() public {
        _rateScenario(true, 6, type(uint64).max, "rateMax");
    }

    function test_parity_rate_quarter_tick_native() public {
        _rateScenario(false, 18, 1 << 30, "rateQuarterTick");
    }

\\1""",
    s,
)
assert "feeDuration" not in s, [l for l in s.splitlines() if "feeDuration" in l]
(here / "ZeroSeedLaunchSdkParityV2.t.sol").write_text(s)
